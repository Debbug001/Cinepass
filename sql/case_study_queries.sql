USE MOVIE_BOOKING_SYSTEM;

-- 1. JOIN: Movie title, show date/time and screen.
SELECT M.TITLE, S.SHOW_DATE, S.SHOW_TIME, SC.SCREEN_NAME
FROM MOVIE M
JOIN SHOWS S ON M.MOVIE_ID = S.MOVIE_ID
JOIN SCREEN SC ON S.SCREEN_ID = SC.SCREEN_ID;

-- 2. JOIN: Movie, theatre, location and screen.
SELECT M.TITLE, T.THEATRE_NAME, T.LOCATION, SC.SCREEN_NAME
FROM MOVIE M
JOIN SHOWS S ON M.MOVIE_ID = S.MOVIE_ID
JOIN SCREEN SC ON S.SCREEN_ID = SC.SCREEN_ID
JOIN THEATRE T ON SC.THEATRE_ID = T.THEATRE_ID;

-- 3. JOIN: Ticket, seat and booking.
SELECT TK.TICKET_ID, TK.BOOKING_ID, ST.SEAT_NUMBER, ST.SEAT_TYPE,
       B.BOOKING_DATE, B.TOTAL_AMOUNT
FROM Ticket TK
JOIN SEAT ST ON TK.SEAT_ID = ST.SEAT_ID
JOIN Booking B ON TK.BOOKING_ID = B.BOOKING_ID;

-- 4. Aggregate: number of movies.
SELECT COUNT(*) AS TOTAL_MOVIES FROM MOVIE;

-- 5. Aggregate: average movie duration.
SELECT AVG(DURATION) AS AVERAGE_MOVIE_DURATION FROM MOVIE;

-- 6. Aggregate + JOIN: revenue grouped by theatre.
SELECT T.THEATRE_NAME, SUM(B.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM Booking B
JOIN SHOWS S ON B.SHOW_ID = S.SHOW_ID
JOIN SCREEN SC ON S.SCREEN_ID = SC.SCREEN_ID
JOIN THEATRE T ON SC.THEATRE_ID = T.THEATRE_ID
GROUP BY T.THEATRE_ID, T.THEATRE_NAME;

-- 7. Subquery: movies longer than average.
SELECT TITLE, DURATION
FROM MOVIE
WHERE DURATION > (SELECT AVG(DURATION) FROM MOVIE);

-- 8. Subquery: bookings above the average booking amount.
SELECT BOOKING_ID, BOOKING_DATE, TOTAL_AMOUNT
FROM Booking
WHERE TOTAL_AMOUNT > (SELECT AVG(TOTAL_AMOUNT) FROM Booking);

-- 9. Subquery: longest movie(s).
SELECT TITLE, DURATION
FROM MOVIE
WHERE DURATION = (SELECT MAX(DURATION) FROM MOVIE);
